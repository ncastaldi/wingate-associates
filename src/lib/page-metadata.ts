import type { Metadata } from "next";

export const SITE_NAME = "Wingate Associates";

// Placeholder like the page copy: revise with the real Home copy.
export const HOME_DESCRIPTION =
  "Independent consulting practice. Services, engagement models and how to get in touch.";

const SHARE_IMAGE = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: SITE_NAME,
};

type PageMetadataInput = {
  // Omit on the home page, which uses the bare site name.
  title?: string;
  description: string;
  // Path from the site root, e.g. "/services". Resolved against metadataBase.
  // Omit in the root layout so pages without their own metadata (such as the
  // 404) do not inherit another page's canonical URL.
  path?: string;
};

// Next merges metadata shallowly, so a page that sets `openGraph` replaces
// the layout's whole object. Build every page's block here so they stay
// complete and consistent, including the image: a page-level `openGraph`
// also drops the image generated by src/app/opengraph-image.tsx.
export function pageMetadata({ title, description, path }: PageMetadataInput): Metadata {
  const fullTitle = title ? `${title} | ${SITE_NAME}` : SITE_NAME;
  return {
    title: { absolute: fullTitle },
    description,
    ...(path && { alternates: { canonical: path } }),
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: "en_US",
      title: fullTitle,
      description,
      ...(path && { url: path }),
      images: [SHARE_IMAGE],
    },
    twitter: { card: "summary_large_image", title: fullTitle, description, images: [SHARE_IMAGE] },
  };
}
